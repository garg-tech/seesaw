#!/usr/bin/env python3
"""Rebuild the result tables from the raw `vllm bench serve` files in results/.

  python evaluation/make_tables.py                  # Markdown, all configs, both tests
  python evaluation/make_tables.py --metric ttft    # median time to first token (s)
  python evaluation/make_tables.py --latex          # LaTeX rows, as used in the report

Every number is read from results/<config>/<test>_n<concurrency>.json. A level whose
result had failed requests is shown with a '!' and should not be quoted.
Ratios are against the first config named in --vs (default tp2, vLLM's TP2).
"""
import argparse
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LEVELS = [1, 2, 4, 8, 16, 32, 64, 128]
CONFIGS = {
    "tp2": "vLLM TP2",
    "pp2": "vLLM PP2",
    "engine_tp_f": "Own TP",
    "engine_pp_f": "Own PP 26/22",
    "seesaw_26f": "Seesaw 26/22",
    "seesaw_28L": "Seesaw 28/20 lean",
}
METRICS = {
    "total": ("total_token_throughput", 1, "{:.0f}", "total tok/s"),
    "output": ("output_throughput", 1, "{:.0f}", "output tok/s"),
    "ttft": ("median_ttft_ms", 1e-3, "{:.1f}", "median TTFT (s)"),
    "tpot": ("median_tpot_ms", 1, "{:.1f}", "median TPOT (ms)"),
}


def load(config, test, n):
    path = os.path.join(ROOT, "results", config, f"{test}_n{n}.json")
    if not os.path.exists(path):
        return None, False
    d = json.load(open(path))
    return d, d.get("failed", 0) == 0 and d["completed"] == d.get("num_prompts", d["completed"])


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--configs", nargs="+", default=list(CONFIGS))
    p.add_argument("--tests", nargs="+", default=["in6k_out512", "in6k_out1024"])
    p.add_argument("--metric", choices=METRICS, default="total")
    p.add_argument("--vs", default="tp2", help="config the ratio column divides by ('' for none)")
    p.add_argument("--latex", action="store_true")
    a = p.parse_args()
    key, scale, fmt, label = METRICS[a.metric]
    for test in a.tests:
        cols = [CONFIGS.get(c, c) for c in a.configs]
        if a.vs and a.metric in ("total", "output"):
            cols += [f"{CONFIGS.get(a.configs[-1], a.configs[-1])} / {CONFIGS.get(a.vs, a.vs)}"]
        if a.latex:
            print(f"% {test}, {label}; generated by evaluation/make_tables.py")
        else:
            print(f"\n{test}, {label}\n")
            print("| c | " + " | ".join(cols) + " |")
            print("|---" * (len(cols) + 1) + "|")
        for n in LEVELS:
            row, vals = [], {}
            for c in a.configs:
                d, ok = load(c, test, n)
                if d is None:
                    row.append("--")
                    continue
                v = d[key] * scale
                vals[c] = v
                row.append(fmt.format(v) + ("" if ok else "!"))
            if a.vs and a.metric in ("total", "output"):
                last = a.configs[-1]
                row.append(f"{vals[last] / vals[a.vs]:.2f}" if last in vals and a.vs in vals else "--")
            if a.latex:
                print(f"{n} & " + " & ".join(row) + r" \\")
            else:
                print(f"| {n} | " + " | ".join(row) + " |")


if __name__ == "__main__":
    main()
